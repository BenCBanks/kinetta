"""Generate matching app/site design tokens. CI --check detects drift; no external dependencies."""
import json
import pathlib
import sys
root = pathlib.Path(__file__).resolve().parents[2]
tokens = json.loads((root / 'docs/design-tokens.json').read_text())
def colors(theme):
    return '\n'.join(f'  --color-{key}: {value};' for key, value in tokens[theme].items())
scale = '\n'.join(f'  --{key}: {value};' for key, value in tokens['scale'].items())
fonts = '\n'.join(f'  --font-{key}: {value};' for key, value in tokens['fonts'].items())
css = ('/* Generated by dev/design/build_tokens.py from docs/design-tokens.json. Edit the JSON. */\n'
       ':root {\n' + colors('light') + '\n' + scale + '\n' + fonts + '\n  color-scheme: light;\n}\n'
       '@media (prefers-color-scheme: dark) { :root:not([data-theme="light"]) {\n' + colors('dark') + '\n  color-scheme: dark;\n} }\n'
       ':root[data-theme="dark"] {\n' + colors('dark') + '\n  color-scheme: dark;\n}\n')
for name in ('app/static/theme.css', 'site/assets/theme.css'):
    path = root / name
    if '--check' in sys.argv:
        if not path.exists() or path.read_text() != css:
            sys.exit(f'{name} is out of date. Run python3 dev/design/build_tokens.py')
    else: path.write_text(css)
# Core text/control contrast is checked against actual canonical color pairs.
def luminance(hex_color):
    values = [int(hex_color[i:i+2],16)/255 for i in (1,3,5)]
    linear = [v/12.92 if v<=0.04045 else ((v+0.055)/1.055)**2.4 for v in values]
    return sum(v*w for v,w in zip(linear,(0.2126,0.7152,0.0722)))
for theme in ('light','dark'):
    p=tokens[theme]
    for fg,bg in [('text','canvas'),('text-secondary','surface'),('text-muted','surface'),('brand','canvas'),('on-action','action')]:
        a,b=sorted([luminance(p[fg]),luminance(p[bg])]); ratio=(b+0.05)/(a+0.05)
        if ratio < 4.5: sys.exit(f'{theme}: {fg}/{bg} contrast {ratio:.2f} below 4.5')
print('Design tokens match; core text/action color pairs pass 4.5:1 contrast')
